import { test, expect } from '../fixtures/sceneweaver.fixture'

test('project URL restores editors, autosaves prompts, compares image candidates and replays seeds', async ({ page, api, seedScenario }) => {
  const seeded = await seedScenario('m4_visual')
  const dialogue = await api.generateDialogue(seeded.beat_id!, seeded.character_id!)
  await api.lockScript(dialogue.candidates[0].id)
  const shot = await api.planShot(seeded.beat_id!)
  const projectPath = `/projects/${seeded.project_id}`
  await page.goto(`${projectPath}/shots/${shot.id}`)
  await expect(page.getByTestId('prompt-positive')).toBeVisible()
  await page.getByTestId('prompt-positive').fill('architecture autosave marker, soft light')
  await expect(page.getByTestId('prompt-save-status')).toHaveText('保存済み')
  await page.goto(projectPath)
  await expect(page.getByTestId('project-workflow')).toBeVisible()
  await expect(page.getByTestId('project-primary-next')).toBeVisible()
  await page.evaluate(() => sessionStorage.clear())
  await page.goto(`${projectPath}/shots/${shot.id}`)
  await expect(page.getByTestId('prompt-positive')).toHaveValue('architecture autosave marker, soft light')
  await page.getByTestId('shot-generate').click()
  await expect(page).toHaveURL(new RegExp(`${projectPath}/shots/${shot.id}/generations/`))
  await expect(page.getByTestId('generation-candidate-list').locator('img')).toHaveCount(4)
  const images = page.getByTestId('generation-candidate-list').locator('img')
  for (const img of await images.all()) {
    await expect(img).toBeVisible()
    await expect.poll(() => img.evaluate((node: HTMLImageElement) => node.complete && node.naturalWidth > 0)).toBe(true)
  }
  const seedBefore = await page.getByTestId('generation-provenance').textContent()
  await page.getByTestId('generation-reproduce').click()
  await expect(page.getByTestId('generation-history').locator('li')).toHaveCount(2)
  await expect(page.getByTestId('generation-provenance')).toHaveText(seedBefore ?? '')
  await page.getByTestId('generation-regenerate-same').click()
  await expect(page.getByTestId('generation-history').locator('li')).toHaveCount(3)
  await page.getByTestId('generation-adopt').click()
  await expect(page.getByTestId('generation-adopted-banner')).toBeVisible()
  await page.evaluate(() => sessionStorage.clear())
  await page.goto(`${projectPath}/csp`)
  await expect(page.getByTestId('csp-page-plan').locator('img')).toHaveCount(1)
  await page.getByTestId('csp-build-handoff').click()
  await expect(page.getByTestId('csp-revision')).toContainText('r001')
  await page.goto(`/characters/${seeded.character_id}`)
  await page.getByTestId('character-field-first_person').fill('僕')
  await page.getByTestId('character-save').click()
  await expect(page.getByRole('status')).toHaveText('保存済み')
  await page.reload()
  await expect(page.getByTestId('character-field-first_person')).toHaveValue('僕')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(`${projectPath}/shots/${shot.id}/generations`)
  await expect(page.getByTestId('generation-candidate-list').locator('img')).toHaveCount(4)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/ui-architecture-mobile.png', fullPage: true })
})

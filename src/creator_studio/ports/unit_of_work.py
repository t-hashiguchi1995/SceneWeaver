from __future__ import annotations

from typing import Protocol

from creator_studio.ports.asset_repository import AssetRepository
from creator_studio.ports.asset_tag_repository import AssetTagRepository
from creator_studio.ports.job_repository import JobRepository
from creator_studio.ports.project_repository import ProjectRepository


class CharacterRepository(Protocol):
    def add(self, character: object) -> object: ...
    def get(self, character_id: object) -> object | None: ...
    def list(self) -> list: ...
    def save(self, character: object) -> object: ...


class SceneRepository(Protocol):
    def add(self, scene: object) -> object: ...
    def get(self, scene_id: object) -> object | None: ...
    def list_for_project(self, project_id: object) -> list: ...
    def save(self, scene: object) -> object: ...


class BeatRepository(Protocol):
    def add(self, beat: object) -> object: ...
    def get(self, beat_id: object) -> object | None: ...
    def list_for_scene(self, scene_id: object) -> list: ...


class ScriptEventRepository(Protocol):
    def add(self, event: object) -> object: ...
    def get(self, event_id: object) -> object | None: ...
    def list_for_beat(self, beat_id: object) -> list: ...
    def save(self, event: object) -> object: ...


class MarketplaceRepository(Protocol):
    def add(self, item: object) -> object: ...
    def get(self, item_id: str) -> object | None: ...
    def search(self, query: str = "", *, category: str | None = None) -> list: ...


class OutfitProfileRepository(Protocol):
    def add(self, profile: object) -> object: ...
    def get(self, profile_id: str) -> object | None: ...
    def save(self, profile: object) -> object: ...


class TryOnSessionRepository(Protocol):
    def add(self, session: object) -> object: ...
    def get(self, session_id: str) -> object | None: ...
    def save(self, session: object) -> object: ...


class ShotRepository(Protocol):
    def add(self, shot: object) -> object: ...
    def get(self, shot_id: object) -> object | None: ...
    def save(self, shot: object) -> object: ...
    def list_for_beat(self, beat_id: object) -> list: ...


class RenderPlanRepository(Protocol):
    def add(self, plan: object) -> object: ...
    def get(self, plan_id: str) -> object | None: ...
    def save(self, plan: object) -> object: ...
    def list_for_shot(self, shot_id: object) -> list: ...


class GenerationAttemptRepository(Protocol):
    def add(self, attempt: object) -> object: ...
    def get(self, attempt_id: str) -> object | None: ...
    def list_for_shot(self, shot_id: object) -> list: ...


class PromptDraftRepository(Protocol):
    def add(self, draft: object) -> object: ...
    def get(self, draft_id: str) -> object | None: ...
    def get_for_shot_template(
        self, shot_id: object, template_id: str, template_version: str
    ) -> object | None: ...
    def save(self, draft: object) -> object: ...


class PromptPresetRepository(Protocol):
    def list_enabled(self) -> list: ...


class VisualLibraryMetadataRepository(Protocol):
    def map_by_source(self) -> dict: ...
    def get(self, source_type: str, source_id: str) -> object | None: ...
    def upsert(self, row: object) -> object: ...


class UnitOfWork(Protocol):
    projects: ProjectRepository
    jobs: JobRepository
    assets: AssetRepository
    asset_tags: AssetTagRepository
    characters: CharacterRepository
    scenes: SceneRepository
    beats: BeatRepository
    script_events: ScriptEventRepository
    marketplace: MarketplaceRepository
    outfit_profiles: OutfitProfileRepository
    tryon_sessions: TryOnSessionRepository
    shots: ShotRepository
    render_plans: RenderPlanRepository
    generation_attempts: GenerationAttemptRepository
    prompt_drafts: PromptDraftRepository
    prompt_presets: PromptPresetRepository
    visual_library_metadata: VisualLibraryMetadataRepository

    def __enter__(self) -> UnitOfWork: ...

    def __exit__(self, *exc: object) -> None: ...

    def commit(self) -> None: ...

    def rollback(self) -> None: ...